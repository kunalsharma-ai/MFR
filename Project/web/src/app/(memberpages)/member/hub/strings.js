// engagement features (Nov 2026) keep their text in ./engage/strings.js
Object.assign(en, engage);

const DICTS = { en };
let active = "en";

export function setStringsLanguage(code) {
  active = DICTS[code] ? code : "en";
}

export function t(key, vars) {
  const s = (DICTS[active] && DICTS[active][key]) ?? en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
