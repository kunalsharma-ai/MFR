import { useState } from 'react';
import { Link } from 'react-router-dom';
import Icon from '../components/Icon.jsx';
import PageHero, { PageSeo } from '../components/PageHero.jsx';
import { CtaBand } from '../components/Common.jsx';
import { PAGES } from '../data/pages.js';
import { CONNECT_BRANDS, liveChannels } from '../data/connect.js';
import VideoShowcase from '../sections/VideoShowcase.jsx';

// Scan & Connect (v2.4) — one page with every brand of the Frequent Research family: MyFrequentRewards,
// Turn2Opinion, MyHealthOpinions and Frequent Research Fieldwork Solutions Pvt. Ltd. Each brand gets its own colour
// world, and every channel (website + social profiles) is a 3D card with a scannable QR code, an "Open" link,
// "Copy link" and "Save QR". Links and QR codes come from src/data/connect.js (QRs are generated by
// scripts/generate-qr.mjs). Channels without a confirmed URL are simply not shown.
const page = PAGES.connect;
const crumbs = [{ name: 'Home', path: '/' }, { name: 'Scan & Connect', path: page.path }];
const ICON = { hub: 'hub', google: 'google', threads: 'threads', pinterest: 'pinterest', website: 'globe', youtube: 'youtube', facebook: 'facebook', instagram: 'instagram', linkedin: 'linkedin', x: 'x', whatsapp: 'whatsapp' };
const TINT = { hub: '#7C4DFF', google: '#EA4335', threads: '#101010', pinterest: '#BD081C', website: '#6D5BF7', youtube: '#FF0033', facebook: '#1877F2', instagram: '#E1306C', linkedin: '#0A66C2', x: '#0F1419', whatsapp: '#25D366' };

function QrCube() {
  const faces = CONNECT_BRANDS.filter((b) => b.id !== 'spl').map((b) => ({ b, c: liveChannels(b)[0] })).filter((x) => x.c);
  return (
    <div className="sc sc-qr">
      <span className="qx-glow" />
      <div className="qx-cube">
        {faces.map(({ b, c }, i) => (
          <span key={b.id} className={`qx-face f${i}`} style={{ '--c': b.color, '--c2': b.color2 }}>
            <img src={c.qr} alt={`QR code for ${b.name || b.short} ${c.label || 'website'}`} width="120" height="120" />
            <b>{b.short}</b>
          </span>
        ))}
        <span className="qx-face top" /><span className="qx-face bottom" />
      </div>
      <span className="qx-beam" />
      <span className="qx-phone"><Icon name="mobile" size={30} /><i /></span>
      {['youtube', 'instagram', 'linkedin', 'facebook', 'whatsapp'].map((ic, i) => <span key={ic} className={`qx-chip k${i}`} style={{ '--t': TINT[ic] }}><Icon name={ic} size={16} /></span>)}
    </div>
  );
}

function ChannelCard({ brand, ch, i }) {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try { await navigator.clipboard.writeText(ch.url); } catch {
      const t = document.createElement('textarea'); t.value = ch.url; document.body.appendChild(t); t.select();
      try { document.execCommand('copy'); } catch { /* ignore */ } t.remove();
    }
    setCopied(true);
    setTimeout(() => setCopied(false), 1800);
  };
  const where = ch.id === 'website' ? `${brand.name} website` : `${brand.name} on ${ch.label}`;
  return (
    <li className="qc" style={{ '--t': TINT[ch.id] || brand.color, '--i': i }}>
      <div className="qc-in">
        <p className="qc-top"><span className="qc-ico"><Icon name={ICON[ch.id] || 'link'} size={20} /></span><span className="qc-id"><b>{ch.label}</b><small>{ch.handle}</small></span></p>
        <div className="qc-scan">
          <img src={ch.qr} alt={`QR code to open the ${where}`} width="168" height="168" loading="lazy" />
          <span className="qc-corners" aria-hidden="true"><i /><i /><i /><i /></span>
          <span className="qc-laser" aria-hidden="true" />
        </div>
        <p className="qc-hint">Point your phone camera at the code</p>
        <div className="qc-act">
          <a className="qc-open" href={ch.url} target="_blank" rel="noopener noreferrer" aria-label={`Open the ${where} (opens in a new tab)`}>Open <Icon name="arrow" size={14} /></a>
          <button type="button" onClick={copy} aria-label={`Copy the link to the ${where}`}><Icon name={copied ? 'check' : 'copy'} size={14} /> {copied ? 'Copied' : 'Copy link'}</button>
          <a href={ch.qr} download={`${brand.id}-${ch.id}-qr.svg`} aria-label={`Save the QR code for the ${where}`}><Icon name="arrow" size={14} className="qc-dl" /> Save QR</a>
        </div>
      </div>
    </li>
  );
}

export default function Connect() {
  return (
    <>
      <PageSeo page={page} crumbs={crumbs} />
      <PageHero
        crumbs={crumbs}
        eyebrow="Scan & Connect"
        title={page.h1}
        lead="Every brand of the Frequent Research family in one place: MyFrequentRewards, Turn2Opinion, MyHealthOpinions, Sampledge and Frequent Research — scan a code with your phone camera, or tap to open. Follow for survey alerts, payout tips and research news."
        tagline={[['mobile', 'Point.'], ['sparkle', 'Scan.'], ['link', 'Connected.']]}
        tone="con"
        theme="violet"
        artNode={<QrCube />}
      >
        <nav className="qx-jump" aria-label="Jump to a brand">
          {CONNECT_BRANDS.map((b) => <a key={b.id} href={`#brand-${b.id}`} style={{ '--c': b.color, '--c2': b.color2 }}><b>{b.short}</b>{b.name.replace(' Fieldwork Solutions Pvt. Ltd.', '')}</a>)}
        </nav>
      </PageHero>

      <VideoShowcase />
      {CONNECT_BRANDS.map((b, bi) => {
        const live = liveChannels(b);
        const more = b.channels.length > live.length;
        return (
          <section key={b.id} id={`brand-${b.id}`} className={`section qb qb-${b.id}`} style={{ '--c': b.color, '--c2': b.color2 }} aria-labelledby={`qb-${b.id}`}>
            <div className="container qb-row">
              <header className="qb-head reveal">
                <span className="qb-mono" aria-hidden="true"><span>{b.short}</span></span>
                <p className="eyebrow">{bi === 0 ? 'You are here' : bi === CONNECT_BRANDS.length - 1 ? 'Parent company' : 'Sister brand'}</p>
                <h2 id={`qb-${b.id}`}>{b.name}</h2>
                <p className="qb-tag">{b.tagline}</p>
                <p className="qb-note">{b.note}</p>
                <p className="qb-count"><b>{live.length}</b> {live.length === 1 ? 'channel' : 'channels'} to scan{more ? ' · more channels coming soon' : ''}</p>
              </header>
              <ul className="qc-grid">
                {live.map((ch, i) => <ChannelCard key={ch.id} brand={b} ch={ch} i={i} />)}
              </ul>
            </div>
          </section>
        );
      })}

      <section className="section qx-tips" aria-labelledby="qx-tips-title">
        <div className="container">
          <h2 id="qx-tips-title" className="reveal">Scanning tips</h2>
          <ol className="qx-steps">
            <li><Icon name="mobile" size={22} /><b>Open your camera</b><small>Most phones read QR codes in the normal camera app — no extra app needed.</small></li>
            <li><Icon name="eye" size={22} /><b>Point at the code</b><small>Hold steady for a second until the link appears.</small></li>
            <li><Icon name="shield" size={22} /><b>Check the address</b><small>Our codes only open the official addresses listed on this page.</small></li>
          </ol>
          <p className="qx-back"><Link to="/contact-us">Need help instead? Contact us <Icon name="arrow" size={14} /></Link></p>
        </div>
      </section>
      <CtaBand />
    </>
  );
}
